    @Override
    protected void registerGoals() {
        super.registerGoals();

        this.goalSelector.addGoal(1, new MeleeAttackGoal(this, 1.2, false) {
            @Override
            protected double getAttackReachSqr(LivingEntity entity) {
                return this.mob.getBbWidth() * this.mob.getBbWidth() + entity.getBbWidth();
            }

            @Override
            public boolean canUse() {
                LivingEntity target = this.mob.getTarget();
                if (target instanceof Player player) {
                    if (player.isCreative() || player.isSpectator()) {
                        this.mob.setTarget(null);
                        return false;
                    }
                }
                return target != null && super.canUse();
            }

            @Override
            public boolean canContinueToUse() {
                LivingEntity target = this.mob.getTarget();
                if (target == null || !target.isAlive()) {
                    return false;
                }
                if (target instanceof Player player) {
                    if (player.isCreative() || player.isSpectator()) {
                        this.mob.setTarget(null);
                        return false;
                    }
                }
                return super.canContinueToUse();
            }
        });

        this.goalSelector.addGoal(2, new RandomStrollGoal(this, 1.0D, 20));

        this.goalSelector.addGoal(3, new RandomLookAroundGoal(this));

        this.targetSelector.addGoal(1, new HurtByTargetGoal(this) {
            @Override
            public boolean canUse() {
                LivingEntity target = this.mob.getLastHurtByMob();
                if (target instanceof Player player) {
                    if (player.isCreative() || player.isSpectator()) {
                        return false;
                    }
                }
                return super.canUse();
            }
        });

        this.targetSelector.addGoal(2, new NearestAttackableTargetGoal<>(this, Player.class, true) {
            @Override
            public boolean canUse() {
                LivingEntity currentTarget = this.mob.getTarget();
                if (currentTarget instanceof Player player) {
                    if (player.isCreative() || player.isSpectator()) {
                        this.mob.setTarget(null);
                    }
                }

                LivingEntity target = this.mob.level().getNearestPlayer(
                        this.mob,
                        this.getFollowDistance()
                );

                if (target instanceof Player player) {
                    if (player.isCreative() || player.isSpectator()) {
                        return false;
                    }
                    this.targetMob = target;
                    return true;
                }
                return false;
            }
        });
    }

